def test_template_header_mismatch(tmp_path):
    # Our marker is present (defined name) but the header was edited: the
    # ladder still says 'template' and the strict parser reports row 1.
    path = _edited_template(tmp_path, "hdr.xlsx", [
        ["C1", "", "Dell", "210-BDZY", "PowerEdge R760 Server", 1, "chassis"]],
        header=["Config", "Model", "Vendor", "Part", "Description", "Qty", "Category"])
    assert detect_format(path, "hdr.xlsx") == "template"
    with pytest.raises(TemplateError) as exc:
        parse_file(path, "hdr.xlsx")
    assert exc.value.errors[0].startswith("Row 1: header must be exactly")
    # An 8th column other than Nodes is refused too.
    path = _edited_template(tmp_path, "col8.xlsx", [], header=template.COLUMNS + ["Price"])
    with pytest.raises(TemplateError) as exc:
        template.parse_template(path)
    assert "8th column" in exc.value.errors[0]
    # No marker and no exact header: not our template, nothing else matches.
    wb = Workbook()
    ws = wb.active
    ws.title = "BOM"
    ws.append(["Config", "Model", "Vendor", "Part", "Description", "Qty", "Category"])
    ws.append(["C1", "", "Dell", "210-BDZY", "PowerEdge R760 Server", 1, "chassis"])
    buf = io.BytesIO()
    wb.save(buf)
    path = _write(tmp_path, "nomarker.xlsx", buf.getvalue())
    assert detect_format(path, "nomarker.xlsx") is None
    with pytest.raises(UnrecognizedFormat):
        parse_file(path, "nomarker.xlsx")
    # The exact header alone (marker lost in a re-save) still counts as ours.
    ws.delete_rows(1)
    ws.insert_rows(1)
    for i, label in enumerate(template.COLUMNS, start=1):
        ws.cell(row=1, column=i).value = label
    buf = io.BytesIO()
    wb.save(buf)
    path = _write(tmp_path, "headeronly.xlsx", buf.getvalue())
    assert detect_format(path, "headeronly.xlsx") == "template"


