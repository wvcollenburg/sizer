def _write(tmp_path, name, data):
    path = tmp_path / name
    path.write_bytes(data)
    return str(path)


def _edited_template(tmp_path, name, rows, header=None):
    """Our blank template with rows appended (and optionally a tampered
    header), saved through openpyxl the way a user's spreadsheet tool would."""
    wb = load_workbook(io.BytesIO(template.build_template_bytes()))
    ws = wb[template.SHEET]
    if header is not None:
        for i, value in enumerate(header, start=1):
            ws.cell(row=1, column=i).value = value
    for row in rows:
        ws.append(row)
    buf = io.BytesIO()
    wb.save(buf)
    return _write(tmp_path, name, buf.getvalue())


