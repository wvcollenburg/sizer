@archive_only
@pytest.mark.parametrize("filename", sorted(ARCHIVE_FILES))
def test_archive_fixture_parity(filename):
    fmt, configs = ARCHIVE_FILES[filename]
    path = os.path.join(ARCHIVE, filename)
    assert detect_format(path, filename) == fmt
    bom, got_fmt = parse_file(path, filename)
    assert got_fmt == fmt
    assert [(c.name, c.server_model, c.node_count) for c in bom.configs] == configs
    for cfg in bom.configs:
        assert cfg.components, "config %r has no components" % cfg.name
        for comp in cfg.components:
            assert comp.quantity >= 1 and comp.description
    ours = bom.to_dict()
    assert NormalizedBOM.from_dict(ours).to_dict() == ours

    ref_path = os.path.join(ARCHIVE_NORMALIZED, _safe(filename) + ".json")
    if not os.path.isfile(ref_path):
        assert filename.startswith("Example HC5650D"), "no reference JSON for %s" % filename
        return
    ref = _load(ref_path)
    assert bom.vendor == ref["vendor"]

    mine, theirs = _load_bearing(ours["configs"]), _load_bearing(ref["configs"])
    accepted = ACCEPTED_DEVIATIONS.get(filename, dict(extra=[], missing=[]))
    extra, missing = mine - theirs, theirs - mine
    unexpected_extra = extra - Counter(accepted["extra"])
    unexpected_missing = missing - Counter(accepted["missing"])
    stale_extra = Counter(accepted["extra"]) - extra
    stale_missing = Counter(accepted["missing"]) - missing
    problems = []
    if unexpected_extra:
        problems.append("we emit but SC//Design did not: %s" % sorted(unexpected_extra.elements(), key=str))
    if unexpected_missing:
        problems.append("SC//Design has but we do not: %s" % sorted(unexpected_missing.elements(), key=str))
    if stale_extra or stale_missing:
        problems.append("accepted deviation no longer happens: extra=%s missing=%s"
                        % (sorted(stale_extra.elements(), key=str), sorted(stale_missing.elements(), key=str)))
    assert not problems, "%s\n  %s" % (filename, "\n  ".join(problems))


