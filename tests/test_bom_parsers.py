def _safe(name):
    return re.sub(r"[^\w.\-]", "_", name)


def _load_bearing(configs):
    """Multiset of (category, part number, quantity) over the load-bearing
    categories of a list of config dicts."""
    return Counter((c["category"], c["partNumber"], c["quantity"])
                   for cfg in configs for c in cfg["components"] if c["category"] in LOAD_BEARING)


